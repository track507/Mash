import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { buildBundle, findBundles } from "../src/bundle.mjs";
import { parseStatements } from "../src/statements.mjs";

let dir;

const config = (inputs) => ({ output: "out.js", iFileName: "Book's Name", requiredSheetVersion: "13.2.3", inputs });
const FILES = {
	"a.js": `var iFileName = "a";\nRequiredSheetVersion("13.0.0");\nSpellsList["x"] = { name: "a" };\n`,
	"b.js": `var iFileName = "b";\nRequiredSheetVersion("13.1.0");\nSpellsList["y"] = { name: "b" };\n`,
	"c.js": `var iFileName = "c";\nSpellsList["x"] = { name: "c" };\n`,
	"commented.js": `// keep me\nSpellsList["k"] = {};\n`,
	"broken.js": `SpellsList[ = ;\n`,
	"nosemi.js": `SpellsList["n"] = {}\n`,
	"call.js": `(function () {})();\n`,
	"out.js": `SpellsList["old"] = {};\n`,
};

beforeAll(() => {
	dir = mkdtempSync(path.join(tmpdir(), "mash-bundle-"));
	for (const [name, content] of Object.entries(FILES)) writeFileSync(path.join(dir, name), content);
});

afterAll(() => {
	rmSync(dir, { recursive: true, force: true });
});

describe("buildBundle", () => {
	it("strips iFileName and RequiredSheetVersion and writes one header", () => {
		const out = buildBundle(config(["a.js", "b.js"]), dir);
		expect(out.match(/iFileName/g)).toHaveLength(1);
		expect(out.match(/RequiredSheetVersion\(/g)).toHaveLength(1);
		expect(out).toMatch(/^\/\/ ! Generated by tools\/bundle/);
		expect(out).toContain("// Inputs: a.js, b.js");
		expect(out).toContain(`var iFileName = "Book's Name";`);
		expect(out).toContain(`RequiredSheetVersion("13.2.3");`);
	});

	it("keeps input order", () => {
		const out = buildBundle(config(["b.js", "a.js"]), dir);
		expect(parseStatements(out).map((statement) => statement.key)).toEqual([
			"var iFileName",
			`RequiredSheetVersion("13.2.3")`,
			`SpellsList["y"]`,
			`SpellsList["x"]`,
		]);
	});

	it("ends in exactly one newline", () => {
		expect(buildBundle(config(["a.js"]), dir)).toMatch(/[^\n]\n$/);
	});

	it("keeps comments that precede a kept statement", () => {
		expect(buildBundle(config(["commented.js"]), dir)).toContain("// keep me");
	});

	it("drops named statements from one input only", () => {
		const out = buildBundle(config([{ file: "a.js", exclude: [`SpellsList["x"]`] }, "c.js"]), dir);
		const kept = parseStatements(out).filter((statement) => statement.key === `SpellsList["x"]`);
		expect(kept).toHaveLength(1);
		expect(out).toContain(`name: "c"`);
		expect(out).not.toContain(`name: "a"`);
	});

	it("names object inputs in the header", () => {
		expect(buildBundle(config([{ file: "a.js", exclude: [`SpellsList["x"]`] }, "c.js"]), dir)).toContain("// Inputs: a.js, c.js");
	});

	it("throws naming the key when an exclude matches nothing", () => {
		expect(() => buildBundle(config([{ file: "a.js", exclude: [`SpellsList["typo"]`] }]), dir)).toThrow(/typo/);
	});

	it("throws naming the file for a missing or unparseable input", () => {
		expect(() => buildBundle(config(["gone.js"]), dir)).toThrow(/gone\.js/);
		expect(() => buildBundle(config(["broken.js"]), dir)).toThrow(/broken\.js/);
	});

	it("throws when the output is listed as an input", () => {
		expect(() => buildBundle(config(["out.js"]), dir)).toThrow(/output/);
	});

	it("throws when joining inputs would merge two statements", () => {
		expect(() => buildBundle(config(["nosemi.js", "call.js"]), dir)).toThrow(/nosemi\.js|merge/);
	});

	it("produces byte-identical LF output for CRLF and LF inputs", () => {
		const lf = `SpellsList["q"] = {\n\tname: "q",\n};\n// tail\n`;
		const crlf = lf.replace(/\n/g, "\r\n");
		const fromLf = buildBundle(config(["same.js"]), dir, () => lf);
		const fromCrlf = buildBundle(config(["same.js"]), dir, () => crlf);
		expect(fromCrlf).toBe(fromLf);
		expect(fromCrlf).not.toContain("\r");
	});

	it("reads through the injected reader with the joined path", () => {
		const seen = [];
		buildBundle(config(["a.js"]), "book", (file) => {
			seen.push(file.split(path.sep).join("/"));
			return "";
		});
		expect(seen).toEqual(["book/a.js"]);
	});
});

describe("findBundles", () => {
	it("finds bundle.json files under the edition folders only", () => {
		const root = path.join(dir, "root");
		mkdirSync(path.join(root, "2014", "Book"), { recursive: true });
		mkdirSync(path.join(root, "tools", "x"), { recursive: true });
		writeFileSync(path.join(root, "2014", "Book", "bundle.json"), JSON.stringify(config(["a.js"])));
		writeFileSync(path.join(root, "tools", "x", "bundle.json"), JSON.stringify(config(["a.js"])));
		const found = findBundles(root);
		expect(found).toHaveLength(1);
		expect(found[0].dir).toBe(path.join(root, "2014", "Book"));
		expect(found[0].config.output).toBe("out.js");
	});
});
