// Builds a whole-book script from the inputs named in a bundle.json
import { existsSync, readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { cleanSource, parseStatements } from "./statements.mjs";

const EDITIONS = ["2014", "2024"];

/**
 * @typedef {string | { file: string, exclude?: string[] }} BundleInput
 * @typedef {{ output: string, iFileName: string, requiredSheetVersion: string, inputs: BundleInput[] }} BundleConfig
 */

/**
 * @param {BundleInput} input
 * @returns {{ file: string, exclude: string[] }}
 */
const inputParts = (input) => (typeof input === "string" ? { file: input, exclude: [] } : { exclude: [], ...input });

/**
 * @param {BundleConfig} config
 * @returns {string[]} Input file names, relative to the bundle.json
 */
export const inputFiles = (config) => config.inputs.map((input) => inputParts(input).file);

/**
 * @param {import("./statements.mjs").Statement} statement
 * @returns {boolean} True for the per-file header statements that the bundle replaces
 */
function isHeader({ key, node }) {
	return key === "var iFileName" || key === "iFileName" || (node.type === "ExpressionStatement" && node.expression.callee?.name === "RequiredSheetVersion");
}

/**
 * Generates a bundle as a string
 *
 * @param {BundleConfig} config
 * @param {string} dir - Folder that input names are relative to
 * @param {(file: string) => string} [read] - Reads an input, by default from the file system
 * @returns {string} LF text ending in one newline
 * @throws {Error} Naming the file or key for a missing or unparseable input, an unmatched exclude or an output listed as an input
 */
export function buildBundle(config, dir, read = (file) => readFileSync(file, "utf8")) {
	const parts = [];
	let keptCount = 0;
	for (const input of config.inputs) {
		const { file, exclude } = inputParts(input);
		if (path.posix.normalize(file) === path.posix.normalize(config.output)) throw new Error(`Bundle output ${config.output} is listed as an input`);

		let source;
		try {
			source = cleanSource(read(path.join(dir, file)));
		} catch (error) {
			throw new Error(`Cannot read bundle input ${file}: ${error.message}`, { cause: error });
		}
		let statements;
		try {
			statements = parseStatements(source);
		} catch (error) {
			throw new Error(`Cannot parse bundle input ${file}: ${error.message}`, { cause: error });
		}

		const keys = new Set(statements.map((statement) => statement.key));
		const unmatched = exclude.filter((key) => !keys.has(key));
		if (unmatched.length > 0) throw new Error(`Exclude in ${file} matches nothing: ${unmatched.join(", ")}`);

		const excluded = new Set(exclude);
		const kept = statements.filter((statement) => !isHeader(statement) && !excluded.has(statement.key));
		keptCount += kept.length;
		const text = kept
			.map(({ start, end }) => source.slice(start, end))
			.join("")
			.trim();
		if (text) parts.push(text);
	}

	const header = [
		"// ! Generated by tools/bundle from bundle.json, do not edit",
		`// Inputs: ${inputFiles(config).join(", ")}`,
		`var iFileName = ${JSON.stringify(config.iFileName)};`,
		`RequiredSheetVersion(${JSON.stringify(config.requiredSheetVersion)});`,
	].join("\n");
	const output = `${[header, ...parts].join("\n\n")}\n`;

	// ! An input ending without a semicolon can merge with the next input through automatic semicolon insertion
	const generated = parseStatements(output).length - 2;
	if (generated !== keptCount) throw new Error(`Joining inputs of ${config.output} would merge statements: expected ${keptCount}, found ${generated}`);
	return output;
}

/**
 * @param {string} root - Repository root
 * @returns {{ dir: string, config: BundleConfig }[]} Every bundle under the edition folders
 */
export function findBundles(root) {
	return EDITIONS.flatMap((edition) => {
		const base = path.join(root, edition);
		if (!existsSync(base)) return [];
		return readdirSync(base, { withFileTypes: true, recursive: true })
			.filter((entry) => entry.isFile() && entry.name === "bundle.json")
			.map((entry) => ({ dir: entry.parentPath, config: JSON.parse(readFileSync(path.join(entry.parentPath, entry.name), "utf8")) }));
	});
}
